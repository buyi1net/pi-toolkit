export function subagentFailureLabels(fallback: string, t?: SubagentsTranslate): ToolCardFailureLabels {
  const byCode: Record<string, string> = {};
  for (const code of SUBAGENT_FAILURE_CODES) {
    const key = `module.subagents.failure.${code}` as SubagentsMessageKey;
    byCode[code] = t?.(key) ?? EN[key];
  }
  return { fallback, byCode };
}

